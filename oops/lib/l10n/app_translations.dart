  /// Translate a given key based on current locale
  static String tr(BuildContext context, String key) {
    final locale = Localizations.localeOf(context);
    final langCode = locale.languageCode.toLowerCase();

    if (_localizedValues.containsKey(langCode) && _localizedValues[langCode]!.containsKey(key)) {
      return _localizedValues[langCode]![key]!;
    }
    // Fallback to English
    return _localizedValues['en']?[key] ?? key;
  }

  /// Translates dynamic category or service names from backend if matching key exists
  static String getLocalizedName(BuildContext context, String rawName) {
    if (rawName.isEmpty) return rawName;
    final normalizedKey = rawName.toLowerCase().replaceAll(' ', '_').replaceAll('&', 'and');
    final translated = tr(context, normalizedKey);
    if (translated != normalizedKey) {
      return translated;
    }
    return rawName;
  }
}

/// Extension on String to make translating super easy: `'home'.tr(context)`
extension TranslationExtension on String {
  String tr(BuildContext context) => AppTranslations.tr(context, this);
}
